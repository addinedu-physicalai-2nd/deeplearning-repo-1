-- ====================================================
-- 스마트 병동 모니터링 시스템 초기화 스크립트
-- 데이터베이스: hospital_monitoring
-- ====================================================

-- 1. 데이터베이스 생성 및 선택
CREATE DATABASE IF NOT EXISTS hospital_monitoring CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE hospital_monitoring;

-- 2. 기존 테이블 삭제 (외래키 의존성 순서 준수)
DROP TABLE IF EXISTS stretch_logs;
DROP TABLE IF EXISTS gait_logs;
DROP TABLE IF EXISTS fall_logs;
DROP TABLE IF EXISTS patients;

-- ----------------------------------------------------
-- 3. 전체 환자 기본 정보 테이블 (patients)
-- ----------------------------------------------------
CREATE TABLE patients (
    id INT AUTO_INCREMENT PRIMARY KEY COMMENT '환자 고유 번호 (PK)',
    name VARCHAR(50) NOT NULL COMMENT '이름',
    gender CHAR(1) COMMENT '성별 (M/F)',
    birth_date DATE COMMENT '생년월일',
    age INT COMMENT '나이',
    admit_date DATE COMMENT '입소일',
    room_number VARCHAR(50) COMMENT '거주 병동',
    care_grade VARCHAR(20) COMMENT '장기요양등급',
    guardian_name VARCHAR(50) COMMENT '보호자 이름',
    guardian_phone VARCHAR(20) COMMENT '보호자 연락처',
    caregiver_name VARCHAR(50) NOT NULL COMMENT '담당 요양보호사 (Assigned caregiver)',
    notes TEXT COMMENT '특이 사항',
    created_at DATETIME DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB;

-- ----------------------------------------------------
-- 4. 낙상 관련 추가 DB (fall_logs)
-- ----------------------------------------------------
CREATE TABLE fall_logs (
    log_id INT AUTO_INCREMENT PRIMARY KEY COMMENT '낙상 사건 고유 번호',
    patient_id INT NOT NULL COMMENT '환자 고유 번호 (FK)',
    camera_id VARCHAR(50) COMMENT '병실 카메라 번호',
    checking_at DATETIME COMMENT '주의(추적 불안정) 단계 진입 시각',
    alert_at DATETIME COMMENT '낙상 확정 시각 (팝업 알림)',
    status VARCHAR(20) DEFAULT '대기' COMMENT '대응 여부 (대기/확인/처리완료)',
    resolved_at DATETIME COMMENT '처리 완료 시각',
    CONSTRAINT fk_fall_patient FOREIGN KEY (patient_id)
        REFERENCES patients(id) ON UPDATE CASCADE ON DELETE RESTRICT
) ENGINE=InnoDB;

-- ----------------------------------------------------
-- 5. 보행 관련 추가 DB (gait_logs)
--    규칙: normal + abnormal + parkinsons + stroke + myopathic + antalgic = 100.00%
-- ----------------------------------------------------
CREATE TABLE gait_logs (
    log_id INT AUTO_INCREMENT PRIMARY KEY COMMENT '보행 측정 고유 번호',
    patient_id INT NOT NULL COMMENT '환자 고유 번호 (FK)',
    camera_id VARCHAR(50) COMMENT '보행 측정 카메라 번호',
    checking_at DATETIME DEFAULT CURRENT_TIMESTAMP COMMENT '보행 진단 시작 시간',
    normal DECIMAL(5,2) COMMENT '정상 보행 분포도 (%)',
    abnormal DECIMAL(5,2) COMMENT '일반 이상 보행 분포도 (%) - 비질환성 걸음걸이 이상',
    parkinsons DECIMAL(5,2) COMMENT '파킨슨 보행 분포도 (%)',
    stroke DECIMAL(5,2) COMMENT '뇌졸중/편마비 분포도 (%)',
    myopathic DECIMAL(5,2) COMMENT '근병증 보행 분포도 (%)',
    antalgic DECIMAL(5,2) COMMENT '통증 회피 보행 분포도 (%)',
    CONSTRAINT fk_gait_patient FOREIGN KEY (patient_id)
        REFERENCES patients(id) ON UPDATE CASCADE ON DELETE RESTRICT
) ENGINE=InnoDB;

-- ----------------------------------------------------
-- 6. 스트레칭 관련 추가 DB (stretch_logs)
-- ----------------------------------------------------
CREATE TABLE stretch_logs (
    log_id INT AUTO_INCREMENT PRIMARY KEY COMMENT '스트레칭 로그 고유 번호',
    patient_id INT NOT NULL COMMENT '환자 고유 번호 (FK)',
    camera_id VARCHAR(50) COMMENT '스트레칭 측정 카메라 번호',
    checking_at DATETIME DEFAULT CURRENT_TIMESTAMP COMMENT '스트레칭 발생 시간',
    straching_id INT COMMENT '스트레칭 운동 종류 ID (1:목, 2:어깨, 3:허리, 4:무릎 등)',
    accuracy_id DECIMAL(5,2) COMMENT '스트레칭 번호당 정확도 (0~100%)',
    CONSTRAINT fk_stretch_patient FOREIGN KEY (patient_id)
        REFERENCES patients(id) ON UPDATE CASCADE ON DELETE RESTRICT
) ENGINE=InnoDB;

